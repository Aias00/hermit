import CTailcat
import Foundation

/// Public metadata only. A complete tc… address contains a secret PSK.
public struct TailcatAddressMetadata: Equatable, Sendable {
    public let serverPublicKey: String
    public let hasPresharedKey: Bool
}

public struct TailcatClientKey: Sendable, CustomStringConvertible, CustomDebugStringConvertible {
    public let privateKey: String
    public let publicKey: String
    public var description: String { "TailcatClientKey(privateKey: <redacted>)" }
    public var debugDescription: String { description }
}

/// These calls are local: they never start a tunnel or fetch a relay map.
public enum TailcatIdentity {
    public static func parseAddress(_ address: String) throws -> TailcatAddressMetadata {
        try NativeAPI.requireABI()
        // Reject embedded NULs rather than validating a truncated C string.
        guard address.hasPrefix("tc"), (3...65_536).contains(address.utf8.count),
              address.utf8.allSatisfy({ $0 > 0x20 && $0 < 0x7f }) else {
            throw TailcatSSHTransportError.invalidAddress
        }
        var output: UnsafeMutablePointer<CChar>?
        let status = address.withCString { pointer in
            tc_address_parse(UnsafeMutablePointer(mutating: pointer), &output, nil)
        }
        defer { tc_free(output) }
        guard status == TC_OK, let json = NativeAPI.dictionary(output),
              let key = json["public_key"] as? String, !key.isEmpty,
              let disco = json["disco_public_key"] as? String,
              let discoBytes = disco.split(separator: ":").last,
              discoBytes.count == 64, discoBytes.contains(where: { $0 != "0" }),
              let hasPSK = json["has_preshared_key"] as? Bool else {
            throw TailcatSSHTransportError.invalidAddress
        }
        return TailcatAddressMetadata(serverPublicKey: key, hasPresharedKey: hasPSK)
    }

    public static func generateClientKey() throws -> TailcatClientKey {
        try NativeAPI.requireABI()
        var output: UnsafeMutablePointer<CChar>?
        let status = tc_key_generate(&output, nil)
        defer { tc_free(output) }
        try NativeAPI.check(status, operation: .generateKey)
        guard let json = NativeAPI.dictionary(output),
              let secret = json["private_key"] as? String,
              let publicKey = json["public_key"] as? String else {
            throw TailcatSSHTransportError.invalidClientKey
        }
        return TailcatClientKey(privateKey: secret, publicKey: publicKey)
    }

    public static func publicKey(forPrivateKey privateKey: String, address: String) throws -> String {
        _ = try parseAddress(address)
        let client = try NativeAPI.makeClient(address: address, privateKey: privateKey)
        defer { tc_close(client, nil) }
        var output: UnsafeMutablePointer<CChar>?
        let status = tc_info(client, 0, &output, nil)
        defer { tc_free(output) }
        try NativeAPI.check(status, operation: .clientInfo)
        guard let json = NativeAPI.dictionary(output), let key = json["public_key"] as? String else {
            throw TailcatSSHTransportError.invalidClientKey
        }
        return key
    }
}

public enum TailcatNativeOperation: String, Equatable, Sendable {
    case generateKey, createClient, clientInfo, createToken, dial, read, write
}

/// Never carries the C API's error text: it can include a secret address or key.
public enum TailcatSSHTransportError: Error, Equatable, LocalizedError, Sendable {
    case invalidAddress, invalidClientKey, invalidPort, invalidTimeout, unsupportedABI
    case nativeFailure(operation: TailcatNativeOperation, code: Int32)
    case bridgeFailure(code: Int32)
    case connectionClosed, backpressureExceeded

    public var isTimeout: Bool {
        if case .nativeFailure(_, let code) = self { return code == TC_TIMEOUT }
        return false
    }

    public var isRetryable: Bool {
        switch self {
        case .invalidAddress, .invalidClientKey, .invalidPort, .invalidTimeout, .unsupportedABI:
            return false
        case .nativeFailure(_, let code):
            return code != TC_INVALID_ARGUMENT && code != TC_CANCELLED
        case .bridgeFailure, .connectionClosed, .backpressureExceeded:
            return true
        }
    }

    public var errorDescription: String? {
        switch self {
        case .invalidAddress: return "The Tailcat address is invalid. Paste the complete address generated by the server."
        case .invalidClientKey: return "The Tailcat client key is invalid. Reconfigure this connection."
        case .invalidPort: return "Enter a Tailcat SSH port from 1 to 65535."
        case .invalidTimeout: return "The Tailcat connection deadline is invalid."
        case .unsupportedABI: return "This Tailcat library version is not supported."
        case .nativeFailure(_, let code) where code == TC_TIMEOUT:
            return "Tailcat timed out. Check that the server is running and this device is allowed."
        case .nativeFailure(let operation, let code):
            return "Tailcat could not complete \(operation.rawValue) (code \(code))."
        case .bridgeFailure(let code): return "The Tailcat connection could not transfer data (code \(code))."
        case .connectionClosed: return "The Tailcat connection closed. Reconnect to continue."
        case .backpressureExceeded: return "The Tailcat connection is too slow to accept queued data. Reconnect to continue."
        }
    }
}

enum NativeAPI {
    static func requireABI() throws {
        guard tc_abi_version() == 1 else { throw TailcatSSHTransportError.unsupportedABI }
    }

    static func dictionary(_ pointer: UnsafeMutablePointer<CChar>?) -> [String: Any]? {
        guard let pointer, let data = String(cString: pointer).data(using: .utf8) else { return nil }
        return (try? JSONSerialization.jsonObject(with: data)) as? [String: Any]
    }

    static func check(_ status: Int32, operation: TailcatNativeOperation) throws {
        if status == TC_CANCELLED { throw CancellationError() }
        guard status == TC_OK else { throw TailcatSSHTransportError.nativeFailure(operation: operation, code: status) }
    }

    static func makeClient(address: String, privateKey: String) throws -> UInt64 {
        guard !privateKey.isEmpty, privateKey.utf8.count <= 512,
              privateKey.utf8.allSatisfy({ $0 > 0x20 && $0 < 0x7f }) else {
            throw TailcatSSHTransportError.invalidClientKey
        }
        let data = try JSONSerialization.data(withJSONObject: ["address": address, "key": privateKey])
        let configuration = String(decoding: data, as: UTF8.self)
        var client: UInt64 = 0
        let status = configuration.withCString { pointer in
            tc_client_new(UnsafeMutablePointer(mutating: pointer), &client, nil)
        }
        guard status == TC_OK else {
            if client != 0 { tc_close(client, nil) }
            if status == TC_INVALID_ARGUMENT { throw TailcatSSHTransportError.invalidClientKey }
            throw TailcatSSHTransportError.nativeFailure(operation: .createClient, code: status)
        }
        return client
    }
}
