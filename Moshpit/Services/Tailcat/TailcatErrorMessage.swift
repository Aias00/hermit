import Foundation
import TailcatSSH

extension TailcatSSHTransportError {
    /// The package keeps typed, redacted diagnostics. Product copy resolves
    /// through the application's language catalog, including SwiftPM errors.
    var moshpitMessage: String {
        switch self {
        case .invalidAddress:
            return String(localized: "The Tailcat address is invalid. Paste the complete address generated by the server.")
        case .invalidClientKey:
            return String(localized: "The Tailcat client key is invalid. Reconfigure this connection.")
        case .invalidPort:
            return String(localized: "Enter a Tailcat SSH port from 1 to 65535.")
        case .invalidTimeout:
            return String(localized: "The Tailcat connection deadline is invalid.")
        case .unsupportedABI:
            return String(localized: "This Tailcat library version is not supported.")
        case .nativeFailure(_, let code):
            if isTimeout {
                return String(localized: "Tailcat timed out. Check that the server is running and this device is allowed.")
            }
            return String(localized: "Tailcat connection failed (code \(Int(code))).")
        case .bridgeFailure(let code):
            return String(localized: "The Tailcat connection could not transfer data (code \(Int(code))).")
        case .connectionClosed:
            return String(localized: "The Tailcat connection closed. Reconnect to continue.")
        case .backpressureExceeded:
            return String(localized: "The Tailcat connection is too slow to accept queued data. Reconnect to continue.")
        }
    }
}
